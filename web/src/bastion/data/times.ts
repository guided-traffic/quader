import { Injectable, inject } from '@angular/core';
import { ApiError } from '../../app/api/problem';
import { BastionData, seg } from './http';

/** The times of a version's documents as the catalogue keeps them (bastion.md R-BAS-103): per kind of document, by JSON pointer. */
interface VersionState {
  readonly times?: Readonly<Record<string, Readonly<Record<string, unknown>>>>;
}

/** How long one read of a version's state serves the documents of the version a page reads with it. */
const SHARED_MS = 5_000;

/**
 * The times the catalogue's builder took out of a version's documents (bastion.md R-BAS-103: built, checked, scanned, synced) and keeps
 * in the version's state document, put back where the main installation's answer has them, so that a view says "Checked 3 hours ago" and
 * "Generated by Quader from the archive, 2 hours ago" at the Bastion as at the main installation (api-and-ui.md Q-UI-1451). One read of
 * the state serves the documents of a version a page reads together; a version without one keeps its documents as they are.
 */
@Injectable({ providedIn: 'root' })
export class VersionTimes {
  private readonly data = inject(BastionData);
  private readonly states = new Map<string, { readonly at: number; readonly state: Promise<VersionState | null> }>();

  /** The document with the times its kind's record names put back. */
  async with<T>(packageId: string, version: string, kind: string, doc: Promise<T>): Promise<T> {
    // After the document: a document that fails asks for no state.
    const value = await doc;
    const state = await this.state(packageId, version);
    const times = state?.times?.[kind];
    if (times && value !== null && typeof value === 'object') {
      for (const [pointer, time] of Object.entries(times)) restore(value as unknown, pointer, time);
    }
    return value;
  }

  private state(packageId: string, version: string): Promise<VersionState | null> {
    const key = `${packageId}\n${version}`;
    const kept = this.states.get(key);
    if (kept && Date.now() - kept.at < SHARED_MS) return kept.state;
    const state = this.data
      .get<VersionState>(`packages/${seg(packageId)}/versions/${seg(version)}/state`)
      .catch((e: unknown) => {
        // No state, or none readable: the documents are shown as they are, and the next read asks again.
        this.states.delete(key);
        if (e instanceof ApiError) return null;
        throw e;
      });
    this.states.set(key, { at: Date.now(), state });
    return state;
  }
}

/** Sets the member a JSON pointer (RFC 6901) names, where its parent exists; a pointer into nothing is left. */
export function restore(doc: unknown, pointer: string, value: unknown): void {
  const parts = pointer
    .split('/')
    .slice(1)
    .map((p) => p.replace(/~1/g, '/').replace(/~0/g, '~'));
  const last = parts.pop();
  if (last === undefined) return;
  let at: unknown = doc;
  for (const p of parts) {
    if (at === null || typeof at !== 'object') return;
    at = (at as Record<string, unknown>)[p];
  }
  if (at !== null && typeof at === 'object') (at as Record<string, unknown>)[last] = value;
}
